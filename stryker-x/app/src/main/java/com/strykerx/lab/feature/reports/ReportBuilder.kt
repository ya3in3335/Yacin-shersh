package com.strykerx.lab.feature.reports

import com.strykerx.lab.core.common.Severity
import com.strykerx.lab.core.database.FindingEntity
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/** Builds offline reports (Markdown) and an AI-ready prompt from findings. */
object ReportBuilder {

    private fun now() = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.US).format(Date())

    private fun sorted(findings: List<FindingEntity>) =
        findings.sortedByDescending { Severity.from(it.severity).rank }

    fun markdown(target: String, findings: List<FindingEntity>): String = buildString {
        appendLine("# STRYKER X — Security Assessment Report")
        appendLine()
        appendLine("- **Target:** $target")
        appendLine("- **Date:** ${now()}")
        appendLine("- **Total findings:** ${findings.size}")
        appendLine()
        appendLine("## Executive Summary")
        appendLine()
        appendLine("| Severity | Count |")
        appendLine("|---|---|")
        for (sev in Severity.entries) {
            appendLine("| ${sev.label} | ${findings.count { Severity.from(it.severity) == sev }} |")
        }
        appendLine()
        appendLine("> Methodology: authorized, non-destructive configuration and passive checks.")
        appendLine("> A finding is only marked Confirmed when supported by reproducible evidence.")
        appendLine()
        if (findings.isEmpty()) {
            appendLine("No findings.")
            return@buildString
        }
        appendLine("## Findings")
        appendLine()
        sorted(findings).forEachIndexed { i, f ->
            appendLine("### ${i + 1}. [${f.severity}] ${f.title}")
            appendLine("- **ID:** ${f.findingCode}")
            appendLine("- **Affected:** ${f.affected}")
            appendLine("- **Detection:** ${f.detectionMethod}")
            appendLine("- **Confidence:** ${f.confidence}")
            appendLine("- **Verification:** ${f.verificationStatus}")
            if (f.evidence.isNotBlank()) appendLine("- **Evidence:** `${f.evidence}`")
            if (f.reproduction.isNotBlank()) appendLine("- **Reproduction:** ${f.reproduction}")
            if (f.remediation.isNotBlank()) appendLine("- **Remediation:** ${f.remediation}")
            appendLine()
        }
        appendLine("---")
        appendLine("_Generated by STRYKER X — for authorized security testing only._")
    }

    /** HackerOne-style single-finding Markdown (first/highest-severity finding). */
    fun hackerOne(target: String, findings: List<FindingEntity>): String {
        val f = sorted(findings).firstOrNull() ?: return "No findings to report."
        return buildString {
            appendLine("**Title:** ${f.title}")
            appendLine()
            appendLine("**Target:** $target")
            appendLine("**Weakness/Severity:** ${f.severity}")
            appendLine()
            appendLine("## Summary")
            appendLine(f.title)
            appendLine()
            appendLine("## Steps To Reproduce")
            appendLine(f.reproduction.ifBlank { "See evidence below." })
            appendLine()
            appendLine("## Evidence")
            appendLine("```")
            appendLine(f.evidence)
            appendLine("```")
            appendLine()
            appendLine("## Impact")
            appendLine("See remediation; verification status: ${f.verificationStatus}.")
            appendLine()
            appendLine("## Remediation")
            appendLine(f.remediation)
        }
    }

    /** Wrap findings in a prompt for an on-device AI app to produce a formal report. */
    fun aiPrompt(target: String, findings: List<FindingEntity>): String = buildString {
        appendLine("You are a cybersecurity expert. Turn the following authorized security")
        appendLine("assessment findings into a professional report ready for the organization:")
        appendLine("1) Executive summary for management.")
        appendLine("2) A severity-ordered findings table with impact assessment.")
        appendLine("3) Prioritized remediation steps.")
        appendLine("4) General recommendations to improve the security posture.")
        appendLine("Do not invent CVSS scores, proof of exploitation, or affected versions.")
        appendLine()
        appendLine("=== RAW FINDINGS ===")
        append(markdown(target, findings))
    }
}
